#!/usr/bin/env python3
"""Aggregate harness result records into paper-ready tables.

Reads every results/*.json written by the C++ harness (raw records are never
edited) and emits:
  - a CSV with one row per run (cell x precision x concurrency x distribution)
  - a markdown summary grouped by cell, for the paper / README

Cost per 1M output tokens is taken from the harness record when the run was
launched with --hourly-usd; otherwise it is recomputed from --prices.

    python3 analysis/aggregate.py results/ --out-csv analysis/summary.csv \
        --out-md analysis/summary.md
"""
from __future__ import annotations

import argparse
import csv
import io
import json
from pathlib import Path

FIELDS = ["cell", "precision", "instance", "model", "concurrency",
          "prompt_tokens", "distribution", "requests_ok", "ttft_ms_p50",
          "ttft_ms_p99", "tpot_ms_p50", "tpot_ms_p99",
          "throughput_tokens_per_s", "slo_goodput",
          "cost_per_1m_output_tokens_usd", "file"]


def load_rows(results_dir: Path) -> list[dict]:
    rows = []
    for path in sorted(results_dir.glob("*.json")):
        try:
            rec = json.loads(path.read_text())
        except (json.JSONDecodeError, OSError):
            continue
        cfg, agg = rec.get("config", {}), rec.get("aggregates", {})
        if not cfg or not agg:
            continue
        rows.append({
            "cell": cfg.get("cell"), "precision": cfg.get("precision"),
            "instance": cfg.get("instance"), "model": cfg.get("model"),
            "concurrency": cfg.get("concurrency"),
            "prompt_tokens": cfg.get("prompt_tokens"),
            "distribution": cfg.get("distribution"),
            "requests_ok": agg.get("requests_ok"),
            "ttft_ms_p50": round(agg.get("ttft_ms_p50", 0), 2),
            "ttft_ms_p99": round(agg.get("ttft_ms_p99", 0), 2),
            "tpot_ms_p50": round(agg.get("tpot_ms_p50", 0), 3),
            "tpot_ms_p99": round(agg.get("tpot_ms_p99", 0), 3),
            "throughput_tokens_per_s": round(
                agg.get("throughput_tokens_per_s", 0), 1),
            "slo_goodput": agg.get("slo_goodput"),
            "cost_per_1m_output_tokens_usd": (
                round(agg["cost_per_1m_output_tokens_usd"], 4)
                if "cost_per_1m_output_tokens_usd" in agg else None),
            "file": path.name,
        })
    return rows


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results_dir")
    ap.add_argument("--out-csv", default="analysis/summary.csv")
    ap.add_argument("--out-md", default="analysis/summary.md")
    args = ap.parse_args()

    rows = load_rows(Path(args.results_dir))
    if not rows:
        print("no harness records found")
        return

    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=FIELDS)
    writer.writeheader()
    writer.writerows(rows)
    Path(args.out_csv).write_text(buf.getvalue())

    header = "| " + " | ".join(FIELDS[:-1]) + " |"
    sep = "|" + "---|" * (len(FIELDS) - 1)
    lines = ["# Run summary (generated by analysis/aggregate.py)", "",
             header, sep]
    for r in rows:
        lines.append("| " + " | ".join(str(r[f]) for f in FIELDS[:-1]) + " |")
    Path(args.out_md).write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} runs -> {args.out_csv}, {args.out_md}")


if __name__ == "__main__":
    main()
